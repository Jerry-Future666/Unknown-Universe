// ============================================================
// Unknown Universe v0.6
// Particle / Scene Engine
//
// Engine
//
// 当前负责：
// 1. Canvas
// 2. 时间循环
// 3. 摄像机基础状态
// 4. 场景对象管理
// 5. 统一 Renderer
//
// 注意：
// Planet / Ring 不再直接负责最终绘制。
// Renderer 统一处理所有粒子的：
// 投影 → 深度排序 → 绘制
// ============================================================


import { CONFIG } from "./config.js";
import { Renderer } from "./renderer.js";



// ============================================================
// Particle Engine
// ============================================================

export class ParticleEngine {

    constructor(canvas) {

        this.canvas =
            canvas;


        this.ctx =
            canvas.getContext(
                "2d",
                {
                    alpha: false
                }
            );


        if (!this.ctx) {

            throw new Error(
                "Canvas 2D context unavailable."
            );

        }



        // ----------------------------------------------------
        // Canvas 尺寸
        // ----------------------------------------------------

        this.width = 0;
        this.height = 0;



        // ----------------------------------------------------
        // 场景对象
        // ----------------------------------------------------

        this.objects = [];



        // ----------------------------------------------------
        // 旧粒子接口
        //
        // 暂时保留。
        // 防止旧代码调用时报错。
        //
        // 正式系统不会再依赖它。
        // ----------------------------------------------------

        this.particles = [];



        // ----------------------------------------------------
        // 摄像机
        // ----------------------------------------------------

        this.camera = {

            x: 0,

            y: 0,

            z: 0,

            centerX: 0,

            centerY: 0,

            focalLength: 700

        };



        // ----------------------------------------------------
        // 时间
        // ----------------------------------------------------

        this.time = 0;

        this.running = false;



        // ----------------------------------------------------
        // Renderer
        //
        // Renderer 使用 Engine 的 camera。
        // ----------------------------------------------------

        this.renderer =
            new Renderer(
                this
            );



        // ----------------------------------------------------
        // 初始化尺寸
        // ----------------------------------------------------

        this.resize();



        // ----------------------------------------------------
        // 浏览器尺寸变化
        // ----------------------------------------------------

        window.addEventListener(
            "resize",
            () => {

                this.resize();

            }
        );

    }



    // ========================================================
    // Canvas 尺寸
    // ========================================================

    resize() {

        const dpr =
            Math.min(
                window.devicePixelRatio || 1,
                2
            );



        this.width =
            window.innerWidth;


        this.height =
            window.innerHeight;



        this.canvas.width =
            Math.floor(
                this.width *
                dpr
            );


        this.canvas.height =
            Math.floor(
                this.height *
                dpr
            );



        this.canvas.style.width =
            this.width +
            "px";


        this.canvas.style.height =
            this.height +
            "px";



        // ----------------------------------------------------
        // 使用 CSS 像素作为逻辑坐标。
        // ----------------------------------------------------

        this.ctx.setTransform(
            dpr,
            0,
            0,
            dpr,
            0,
            0
        );



        // ----------------------------------------------------
        // 摄像机屏幕中心
        // ----------------------------------------------------

        this.camera.centerX =
            this.width / 2;


        this.camera.centerY =
            this.height / 2;



        // ----------------------------------------------------
        // 通知场景对象
        // ----------------------------------------------------

        for (
            let i = 0;
            i < this.objects.length;
            i++
        ) {

            const object =
                this.objects[i];


            if (
                object &&
                typeof object.onResize ===
                "function"
            ) {

                object.onResize();

            }

        }

    }



    // ========================================================
    // 添加场景对象
    // ========================================================

    addObject(object) {

        if (!object) {

            return;

        }


        this.objects.push(
            object
        );


        // ----------------------------------------------------
        // Renderer 同步场景对象
        // ----------------------------------------------------

        this.renderer.setObjects(
            this.objects
        );

    }



    // ========================================================
    // 删除场景对象
    // ========================================================

    removeObject(object) {

        const index =
            this.objects.indexOf(
                object
            );


        if (
            index !== -1
        ) {

            this.objects.splice(
                index,
                1
            );

        }


        this.renderer.setObjects(
            this.objects
        );

    }



    // ========================================================
    // 清除场景对象
    // ========================================================

    clearObjects() {

        this.objects.length = 0;


        this.renderer.setObjects(
            this.objects
        );

    }



    // ========================================================
    // 兼容旧粒子接口
    // ========================================================

    addParticle(particle) {

        if (!particle) {

            return;

        }


        this.particles.push(
            particle
        );

    }



    // ========================================================
    // 清除旧粒子
    // ========================================================

    clearParticles() {

        this.particles.length = 0;

    }



    // ========================================================
    // 更新所有场景对象
    // ========================================================

    update(time) {

        for (
            let i = 0;
            i < this.objects.length;
            i++
        ) {

            const object =
                this.objects[i];


            if (
                object &&
                typeof object.update ===
                "function"
            ) {

                object.update(
                    time
                );

            }

        }

    }



    // ========================================================
    // 清空画布
    // ========================================================

    clear() {

        this.ctx.fillStyle =
            CONFIG.background;


        this.ctx.fillRect(
            0,
            0,
            this.width,
            this.height
        );

    }



    // ========================================================
    // 统一渲染
    // ========================================================

    render() {

        this.renderer.render(
            this.ctx
        );

    }



    // ========================================================
    // 单帧
    // ========================================================

    frame(time) {

        this.time =
            time;


        // ----------------------------------------------------
        // 1. 清空上一帧
        // ----------------------------------------------------

        this.clear();



        // ----------------------------------------------------
        // 2. 更新三维世界
        //
        // Planet / Ring 在这里计算：
        //
        // x
        // y
        // z
        //
        // ----------------------------------------------------

        this.update(
            time
        );



        // ----------------------------------------------------
        // 3. Renderer 统一投影
        //
        // 所有粒子进入同一个深度排序队列。
        // ----------------------------------------------------

        this.render();

    }



    // ========================================================
    // 启动
    // ========================================================

    start() {

        if (
            this.running
        ) {

            return;

        }


        this.running =
            true;



        const loop =
            (time) => {

                if (
                    !this.running
                ) {

                    return;

                }


                this.frame(
                    time
                );


                requestAnimationFrame(
                    loop
                );

            };



        requestAnimationFrame(
            loop
        );

    }



    // ========================================================
    // 停止
    // ========================================================

    stop() {

        this.running =
            false;

    }

}
