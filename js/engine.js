import { CONFIG } from "./config.js";


// ============================================================
// Unknown Universe v0.5
// Particle Engine
//
// 负责整个粒子系统的运行。
// 不负责具体的星球、星环和剧情。
// ============================================================

export class ParticleEngine {

    constructor(canvas) {

        this.canvas = canvas;

        this.ctx =
            canvas.getContext("2d", {
                alpha: false
            });


        // ----------------------------------------------------
        // Canvas 尺寸
        // ----------------------------------------------------

        this.width = 0;
        this.height = 0;


        // ----------------------------------------------------
        // 粒子集合
        // ----------------------------------------------------

        this.particles = [];


        // ----------------------------------------------------
        // 系统时间
        // ----------------------------------------------------

        this.time = 0;

        this.lastTime = performance.now();


        // ----------------------------------------------------
        // 摄像机
        //
        // camera.js 完成后会正式接管。
        // 这里先建立兼容接口。
        // ----------------------------------------------------

        this.camera = {

            x: 0,

            y: 0,

            z: 0,

            centerX: 0,

            centerY: 0,

            focalLength: 700

        };


        // ----------------------------------------------------
        // 运行状态
        // ----------------------------------------------------

        this.running = false;


        // ----------------------------------------------------
        // 初始化 Canvas
        // ----------------------------------------------------

        this.resize();

        window.addEventListener(
            "resize",
            () => this.resize()
        );

    }



    // ========================================================
    // Canvas 尺寸调整
    // ========================================================

    resize() {

        const dpr =
            Math.min(
                window.devicePixelRatio || 1,
                2
            );


        this.width =
            window.innerWidth;


        this.height =
            window.innerHeight;


        // ----------------------------------------------------
        // 实际渲染分辨率
        //
        // DPR 最大限制为 2。
        // 手机高分辨率屏幕如果无限提高 Canvas 分辨率，
        // 会明显增加 GPU / CPU 压力。
        // ----------------------------------------------------

        this.canvas.width =
            this.width * dpr;


        this.canvas.height =
            this.height * dpr;


        this.canvas.style.width =
            this.width + "px";


        this.canvas.style.height =
            this.height + "px";


        this.ctx.setTransform(
            dpr,
            0,
            0,
            dpr,
            0,
            0
        );


        // ----------------------------------------------------
        // 摄像机中心
        // ----------------------------------------------------

        this.camera.centerX =
            this.width / 2;


        this.camera.centerY =
            this.height / 2;

    }



    // ========================================================
    // 添加粒子
    // ========================================================

    addParticle(particle) {

        this.particles.push(
            particle
        );

    }



    // ========================================================
    // 批量添加粒子
    // ========================================================

    addParticles(particles) {

        if (!particles) return;


        for (
            let i = 0;
            i < particles.length;
            i++
        ) {

            this.particles.push(
                particles[i]
            );

        }

    }



    // ========================================================
    // 清空粒子
    // ========================================================

    clearParticles() {

        this.particles.length = 0;

    }



    // ========================================================
    // 更新所有粒子
    // ========================================================

    update(time) {

        for (
            let i = 0;
            i < this.particles.length;
            i++
        ) {

            this.particles[i].update(
                time
            );

        }

    }



    // ========================================================
    // 投影所有粒子
    // ========================================================

    project() {

        for (
            let i = 0;
            i < this.particles.length;
            i++
        ) {

            this.particles[i].project(
                this.camera
            );

        }

    }



    // ========================================================
    // 绘制背景
    // ========================================================

    clear() {

        this.ctx.fillStyle =
            CONFIG.background;


        this.ctx.fillRect(
            0,
            0,
            this.width,
            this.height
        );

    }



    // ========================================================
    // 绘制粒子
    //
    // 当前只是基础渲染。
    // planet.js 后面会建立更高级的粒子绘制逻辑。
    // ========================================================

    renderParticles() {

        const ctx =
            this.ctx;


        const color =
            CONFIG.particleColor;



        for (
            let i = 0;
            i < this.particles.length;
            i++
        ) {

            const p =
                this.particles[i];


            if (
                p.screenSize <= 0 ||
                p.screenAlpha <= 0
            ) {

                continue;

            }



            ctx.beginPath();


            ctx.arc(
                p.screenX,
                p.screenY,
                p.screenSize,
                0,
                Math.PI * 2
            );


            const brightness =
                p.getBrightness();


            ctx.fillStyle =
                `rgba(
                    ${color.r},
                    ${color.g},
                    ${color.b},
                    ${brightness}
                )`;


            ctx.fill();

        }

    }



    // ========================================================
    // 单帧渲染
    // ========================================================

    frame(time) {

        // ----------------------------------------------------
        // 时间
        // ----------------------------------------------------

        this.time =
            time;


        // ----------------------------------------------------
        // 清空
        // ----------------------------------------------------

        this.clear();


        // ----------------------------------------------------
        // 更新
        // ----------------------------------------------------

        this.update(
            time
        );


        // ----------------------------------------------------
        // 三维 → 二维投影
        // ----------------------------------------------------

        this.project();


        // ----------------------------------------------------
        // 绘制
        // ----------------------------------------------------

        this.renderParticles();

    }



    // ========================================================
    // 启动引擎
    // ========================================================

    start() {

        if (this.running) {
            return;
        }


        this.running = true;


        const loop =
            (time) => {

                if (!this.running) {
                    return;
                }


                this.frame(
                    time
                );


                requestAnimationFrame(
                    loop
                );

            };


        requestAnimationFrame(
            loop
        );

    }



    // ========================================================
    // 停止引擎
    // ========================================================

    stop() {

        this.running =
            false;

    }

}
