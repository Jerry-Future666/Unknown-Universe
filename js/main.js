// ============================================================
// Unknown Universe v0.5
// Main Entry
//
// 当前场景：
// Planet
// +
// PlanetRing
// ============================================================


import { ParticleEngine } from "./engine.js";
import { Planet } from "./planet.js";
import { PlanetRing } from "./ring.js";



// ============================================================
// Canvas
// ============================================================

const canvas =
    document.getElementById(
        "universe"
    );


if (!canvas) {

    throw new Error(
        "Unknown Universe: Canvas #universe not found."
    );

}



// ============================================================
// Engine
// ============================================================

const engine =
    new ParticleEngine(
        canvas
    );



// ============================================================
// Planet
// ============================================================

const planet =
    new Planet(
        engine
    );



// ============================================================
// Planet Ring
// ============================================================

const ring =
    new PlanetRing(
        engine,
        planet
    );



// ============================================================
// 场景加入顺序
//
// 注意：
// 这里不是最终的空间遮挡系统。
// 当前先让星球和星环同时存在。
// 后续 Scene / Depth Renderer 会统一处理真正的
// 前后空间关系。
// ============================================================

engine.addObject(
    planet
);

engine.addObject(
    ring
);



// ============================================================
// 开发调试接口
// ============================================================

window.UnknownUniverse = {

    engine,

    planet,

    ring

};



// ============================================================
// 启动
// ============================================================

engine.start();



console.log(
    "Unknown Universe v0.5 — Planet + Ring Online."
);
