// ============================================================
// Unknown Universe v0.6
// Camera
//
// 唯一三维 → 二维投影入口
//
// Camera 不负责：
// ❌ Planet
// ❌ Ring
// ❌ 粒子生成
// ❌ 粒子运动
//
// Camera 只负责：
// ✅ 摄像机位置
// ✅ 屏幕中心
// ✅ 透视
// ✅ 三维坐标投影
//
// 后续“钻入星球”的镜头也将在这里扩展。
// ============================================================


import { CONFIG } from "./config.js";



export class Camera {

    constructor() {

        // ====================================================
        // 摄像机世界坐标
        // ====================================================

        this.x = 0;

        this.y = 0;

        this.z = 0;


        // ====================================================
        // 屏幕尺寸
        // ====================================================

        this.width = 0;

        this.height = 0;


        // ====================================================
        // 屏幕中心
        // ====================================================

        this.centerX = 0;

        this.centerY = 0;


        // ====================================================
        // 焦距
        // ====================================================

        this.focalLength =
            700;


        // ====================================================
        // 当前投影安全范围
        // ====================================================

        this.minPerspective =
            0.15;

        this.maxPerspective =
            3;


        // ====================================================
        // 初始化
        // ====================================================

        this.resize(
            window.innerWidth,
            window.innerHeight
        );

    }



    // ========================================================
    // Resize
    // ========================================================

    resize(
        width,
        height
    ) {

        this.width =
            width;

        this.height =
            height;


        this.centerX =
            width / 2;

        this.centerY =
            height / 2;

    }



    // ========================================================
    // 设置摄像机位置
    // ========================================================

    setPosition(
        x = 0,
        y = 0,
        z = 0
    ) {

        this.x = x;

        this.y = y;

        this.z = z;

    }



    // ========================================================
    // 获取深度
    //
    // 当前坐标约定：
    //
    // particle.z 越大
    // = 离摄像机越远
    //
    // particle.z 越小
    // = 越接近摄像机
    // ========================================================

    getDepth(
        particle
    ) {

        return (
            particle.z -
            this.z
        );

    }



    // ========================================================
    // 计算透视比例
    // ========================================================

    getPerspective(
        depth
    ) {

        const denominator =
            this.focalLength +
            depth;


        // ----------------------------------------------------
        // 防止摄像机进入异常深度。
        // ----------------------------------------------------

        if (
            denominator <= 1
        ) {

            return this.maxPerspective;

        }


        const perspective =
            this.focalLength /
            denominator;


        return clamp(
            perspective,
            this.minPerspective,
            this.maxPerspective
        );

    }



    // ========================================================
    // 三维 → 二维
    // ========================================================

    project(
        particle
    ) {

        const depth =
            this.getDepth(
                particle
            );


        const perspective =
            this.getPerspective(
                depth
            );


        // ----------------------------------------------------
        // 保存深度
        // ----------------------------------------------------

        particle.depth =
            depth;


        // ----------------------------------------------------
        // 屏幕坐标
        //
        // 注意：
        // particle.x/y 已经是世界坐标。
        //
        // 所以这里不再添加 Planet.centerX。
        // ----------------------------------------------------

        particle.screenX =
            this.centerX +
            (
                particle.x -
                this.x
            ) *
            perspective;


        particle.screenY =
            this.centerY +
            (
                particle.y -
                this.y
            ) *
            perspective;


        // ----------------------------------------------------
        // 屏幕尺寸
        // ----------------------------------------------------

        particle.screenSize =
            particle.size *
            perspective;


        // ----------------------------------------------------
        // 深度透明度
        // ----------------------------------------------------

        const depthRange =
            CONFIG.space.depthRange;


        const depthFade =
            clamp(
                1 -
                Math.abs(depth) /
                depthRange,
                0.12,
                1
            );


        particle.screenAlpha =
            depthFade;


        // ----------------------------------------------------
        // 是否位于摄像机后方
        // ----------------------------------------------------

        particle.visible =
            (
                depth >
                -this.focalLength * 0.9
            );


        return particle;

    }

}



// ============================================================
// 工具函数
// ============================================================


function clamp(
    value,
    min,
    max
) {

    return Math.max(
        min,
        Math.min(
            max,
            value
        )
    );

}
