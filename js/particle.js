// ============================================================
// Unknown Universe v0.6
// Particle Core
//
// 粒子底层对象
//
// 本版本重要原则：
//
// Particle 不再负责：
// ❌ 星球旋转
// ❌ 星环旋转
// ❌ 空间漂移
// ❌ 三维坐标变换
//
// Particle 只负责：
// ✅ 保存局部 / 世界坐标
// ✅ 保存视觉属性
// ✅ 呼吸效果
// ✅ 保存投影结果
//
// Planet / Ring 决定粒子“在哪里”
// Camera 决定粒子“投影在哪里”
// Renderer 决定粒子“什么时候画”
// ============================================================


import { CONFIG } from "./config.js";



export class Particle {

    constructor(
        x = 0,
        y = 0,
        z = 0
    ) {

        // ====================================================
        // 局部坐标
        //
        // localX/Y/Z 永远属于所属天体自身坐标系。
        // ====================================================

        this.localX = x;
        this.localY = y;
        this.localZ = z;


        // ====================================================
        // 世界坐标
        //
        // Planet / Ring 每一帧负责写入。
        // ====================================================

        this.x = x;
        this.y = y;
        this.z = z;


        // ====================================================
        // 世界坐标缓存
        //
        // 方便调试和后续 Camera 系统。
        // ====================================================

        this.worldX = x;
        this.worldY = y;
        this.worldZ = z;


        // ====================================================
        // 基础视觉尺寸
        // ====================================================

        this.baseSize =
            randomRange(
                0.45,
                1.65
            );


        this.size =
            this.baseSize;


        // ====================================================
        // 基础亮度
        //
        // 注意：
        // 不使用强光晕。
        // ====================================================

        this.baseBrightness =
            randomRange(
                0.22,
                0.78
            );


        this.brightness =
            this.baseBrightness;


        // ====================================================
        // 呼吸效果
        // ====================================================

        this.breathPhase =
            Math.random() *
            Math.PI *
            2;


        this.breathSpeed =
            randomRange(
                0.0003,
                0.001
            );


        this.breath =
            1;


        // ====================================================
        // 天体光照因子
        //
        // Planet 会修改。
        // Ring 默认保持 1。
        // ====================================================

        this.lightFactor =
            1;


        // ====================================================
        // 最终渲染亮度
        // ====================================================

        this.finalBrightness =
            this.baseBrightness;


        // ====================================================
        // 投影结果
        // ====================================================

        this.screenX = 0;

        this.screenY = 0;

        this.screenSize =
            this.baseSize;

        this.screenAlpha = 0;


        // ====================================================
        // 深度
        //
        // Renderer 会根据 camera 重新计算。
        // ====================================================

        this.depth = 0;


        // ====================================================
        // 可见性
        // ====================================================

        this.visible = true;


        // ====================================================
        // 类型标识
        //
        // Planet / Ring 可以覆盖。
        // ====================================================

        this.type =
            "particle";

    }



    // ========================================================
    // 更新视觉状态
    //
    // 重要：
    // 不修改 x / y / z。
    // ========================================================

    updateVisual(time) {

        const breathing =
            Math.sin(
                time *
                this.breathSpeed +
                this.breathPhase
            );


        // ----------------------------------------------------
        // 极轻微呼吸
        //
        // 保持高级感。
        // ----------------------------------------------------

        this.breath =
            1 +
            breathing *
            0.045;


        this.size =
            this.baseSize *
            this.breath;


        // ----------------------------------------------------
        // 亮度只做非常轻微变化。
        // ----------------------------------------------------

        this.brightness =
            this.baseBrightness *
            (
                1 +
                breathing *
                0.035
            );


        // ----------------------------------------------------
        // 最终亮度交给 Renderer 使用。
        // ----------------------------------------------------

        this.finalBrightness =
            this.brightness *
            this.lightFactor;

    }



    // ========================================================
    // 兼容旧系统
    //
    // 旧 Planet / Ring 暂时调用 update() 时不会报错。
    //
    // 但正式 v0.6 系统应该使用：
    //
    // particle.updateVisual(time)
    //
    // ========================================================

    update(time) {

        this.updateVisual(
            time
        );

    }



    // ========================================================
    // 设置世界坐标
    //
    // Planet / Ring 使用。
    // ========================================================

    setWorldPosition(
        x,
        y,
        z
    ) {

        this.x = x;
        this.y = y;
        this.z = z;


        this.worldX = x;
        this.worldY = y;
        this.worldZ = z;

    }



    // ========================================================
    // 获取最终亮度
    // ========================================================

    getBrightness(
        lightFactor = this.lightFactor
    ) {

        return clamp(
            this.brightness *
            lightFactor,
            0,
            1
        );

    }



    // ========================================================
    // 兼容旧 Camera API
    //
    // 正式 Renderer 会直接调用 camera.project().
    //
    // 保留这个函数只是为了避免重构过程中旧代码报错。
    // ========================================================

    project(camera) {

        if (
            camera &&
            typeof camera.project ===
            "function"
        ) {

            camera.project(
                this
            );

        }


        return this;

    }

}



// ============================================================
// 工具函数
// ============================================================


function randomRange(
    min,
    max
) {

    return (
        Math.random() *
        (
            max -
            min
        )
    ) + min;

}



function clamp(
    value,
    min,
    max
) {

    return Math.max(
        min,
        Math.min(
            max,
            value
        )
    );

}
