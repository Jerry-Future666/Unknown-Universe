// ============================================================
// Unknown Universe v0.5
// Planet Ring
//
// 粒子星环系统
//
// 设计目标：
// 1. 环绕天体中部
// 2. 三维倾斜
// 3. 宽粒子带
// 4. 不使用强光晕
// 5. 与星球形成自然空间关系
// 6. 星环与星球共享同一旋转坐标系
// 7. 星环粒子不进行独立漂移
// ============================================================


import { Particle } from "./particle.js";
import { CONFIG } from "./config.js";



export class PlanetRing {

    constructor(
        engine,
        planet
    ) {

        this.engine =
            engine;

        this.planet =
            planet;


        // ----------------------------------------------------
        // 粒子
        // ----------------------------------------------------

        this.particles = [];


        // ----------------------------------------------------
        // 星环尺寸
        // ----------------------------------------------------

        this.innerRadius =
            0;

        this.outerRadius =
            0;


        // ----------------------------------------------------
        // 星环倾角
        //
        // 星环本身保持空间倾斜。
        // 但不会因此脱离星球。
        // ----------------------------------------------------

        this.inclination =
            -0.28;


        // ----------------------------------------------------
        // 当前旋转
        //
        // 注意：
        // 这里不再自己推进 rotation。
        // 每一帧直接读取 Planet 的 rotation。
        // ----------------------------------------------------

        this.rotation =
            0;


        // ----------------------------------------------------
        // 初始化
        // ----------------------------------------------------

        this.resize();

        this.generate();

    }



    // ========================================================
    // 尺寸
    // ========================================================

    resize() {

        const planetRadius =
            this.planet.radius;


        // ----------------------------------------------------
        // 星环内圈
        //
        // 与星球保持一定间距。
        // ----------------------------------------------------

        this.innerRadius =
            planetRadius *
            1.12;


        // ----------------------------------------------------
        // 星环外圈
        //
        // 不做得过于巨大，
        // 防止星环反过来吞掉星球主体。
        // ----------------------------------------------------

        this.outerRadius =
            planetRadius *
            1.78;

    }



    // ========================================================
    // 生成星环粒子
    // ========================================================

    generate() {

        this.particles.length =
            0;


        // ----------------------------------------------------
        // 粒子数量
        // ----------------------------------------------------

        const count =
            1800;


        for (
            let i = 0;
            i < count;
            i++
        ) {

            // ------------------------------------------------
            // 环绕角度
            // ------------------------------------------------

            const angle =
                Math.random() *
                Math.PI *
                2;


            // ------------------------------------------------
            // 星环半径
            // ------------------------------------------------

            const radius =
                randomRingRadius(
                    this.innerRadius,
                    this.outerRadius
                );


            // ------------------------------------------------
            // 基础环面坐标
            // ------------------------------------------------

            const x =
                Math.cos(angle) *
                radius;


            const z =
                Math.sin(angle) *
                radius;


            // ------------------------------------------------
            // 星环宽度
            //
            // 中间较厚，
            // 两侧自然收窄。
            // ------------------------------------------------

            const normalized =
                (
                    radius -
                    this.innerRadius
                ) /
                (
                    this.outerRadius -
                    this.innerRadius
                );


            const bandWidth =
                Math.sin(
                    normalized *
                    Math.PI
                );


            // ------------------------------------------------
            // Y轴厚度
            //
            // 保持很薄，
            // 防止变成一个“粒子甜甜圈”。
            // ------------------------------------------------

            const y =
                randomRange(
                    -22,
                    22
                ) *
                bandWidth;


            // ------------------------------------------------
            // 创建粒子
            // ------------------------------------------------

            const particle =
                new Particle(
                    x,
                    y,
                    z
                );


            // ------------------------------------------------
            // 保存星环原始坐标
            //
            // 后续每一帧都从这里重新计算，
            // 不允许粒子自身漂移。
            // ------------------------------------------------

            particle.ringX =
                x;

            particle.ringY =
                y;

            particle.ringZ =
                z;


            particle.ringRadius =
                radius;


            particle.ringAngle =
                angle;


            // ------------------------------------------------
            // 粒子尺寸
            // ------------------------------------------------

            particle.baseSize *=
                randomRange(
                    0.35,
                    0.75
                );


            // ------------------------------------------------
            // 粒子亮度
            //
            // 星环必须比星球更加克制。
            // ------------------------------------------------

            particle.brightness *=
                randomRange(
                    0.35,
                    0.75
                );


            this.particles.push(
                particle
            );

        }

    }



    // ========================================================
    // 更新
    // ========================================================

    update(time) {

        // ----------------------------------------------------
        // 关键：
        //
        // 星环不再拥有自己的 rotationSpeed。
        //
        // 直接读取星球当前旋转。
        //
        // Planet 转多少，
        // Ring 就转多少。
        // ----------------------------------------------------

        if (
            typeof this.planet.getRotation ===
            "function"
        ) {

            this.rotation =
                this.planet.getRotation();

        }
        else {

            // ------------------------------------------------
            // 兼容旧 Planet。
            //
            // 如果暂时没有 getRotation，
            // 尝试读取公开 rotation。
            // ------------------------------------------------

            this.rotation =
                this.planet.rotation ||
                0;

        }



        // ----------------------------------------------------
        // 旋转三角函数
        // ----------------------------------------------------

        const sinRotation =
            Math.sin(
                this.rotation
            );


        const cosRotation =
            Math.cos(
                this.rotation
            );


        // ----------------------------------------------------
        // 星环倾角
        // ----------------------------------------------------

        const sinInclination =
            Math.sin(
                this.inclination
            );


        const cosInclination =
            Math.cos(
                this.inclination
            );



        // ----------------------------------------------------
        // 更新所有星环粒子
        // ----------------------------------------------------

        for (
            let i = 0;
            i < this.particles.length;
            i++
        ) {

            const particle =
                this.particles[i];


            // ------------------------------------------------
            // 原始星环坐标
            //
            // 注意：
            // 永远从原始坐标重新计算。
            // ------------------------------------------------

            const x =
                particle.ringX;


            const y =
                particle.ringY;


            const z =
                particle.ringZ;



            // ------------------------------------------------
            // 第一阶段：
            // 与星球同步绕 Y 轴旋转
            // ------------------------------------------------

            const rotatedX =
                x *
                cosRotation -
                z *
                sinRotation;


            const rotatedZ =
                x *
                sinRotation +
                z *
                cosRotation;



            // ------------------------------------------------
            // 第二阶段：
            // 星环自身空间倾斜
            //
            // 绕 X 轴。
            // ------------------------------------------------

            const tiltedY =
                y *
                cosInclination -
                rotatedZ *
                sinInclination;


            const tiltedZ =
                y *
                sinInclination +
                rotatedZ *
                cosInclination;



            // ------------------------------------------------
            // 写入 Particle 世界坐标
            // ------------------------------------------------

            particle.baseX =
                rotatedX;


            particle.baseY =
                tiltedY;


            particle.baseZ =
                tiltedZ;



            // ------------------------------------------------
            // 重要：
            //
            // 不再调用：
            //
            // particle.update(time)
            //
            // 因为 Particle.update()
            // 可能让粒子产生独立运动。
            //
            // 星环必须作为一个整体运动。
            // ------------------------------------------------



            // ------------------------------------------------
            // 投影
            // ------------------------------------------------

            particle.project(
                this.engine.camera
            );

        }

    }



    // ========================================================
    // 绘制
    // ========================================================

    render(ctx) {

        // ----------------------------------------------------
        // 根据深度进行基础排序
        //
        // 注意：
        // 这里目前只是星环内部排序。
        //
        // Planet / Ring 之间真正的前后遮挡，
        // 后续由 Scene / Depth Renderer 统一处理。
        // ----------------------------------------------------

        const sorted =
            [...this.particles].sort(
                (a, b) => {

                    return (
                        b.screenSize -
                        a.screenSize
                    );

                }
            );


        const color =
            CONFIG.particleColor;



        // ----------------------------------------------------
        // 绘制
        // ----------------------------------------------------

        for (
            let i = 0;
            i < sorted.length;
            i++
        ) {

            const particle =
                sorted[i];


            // ------------------------------------------------
            // 粒子大小
            // ------------------------------------------------

            const size =
                Math.max(
                    0.3,
                    particle.screenSize
                );


            // ------------------------------------------------
            // 粒子透明度
            //
            // 强制限制上限。
            // 防止星环出现巨大光晕。
            // ------------------------------------------------

            const alpha =
                Math.max(
                    0.08,
                    Math.min(
                        particle.screenAlpha *
                        particle.brightness,
                        0.75
                    )
                );



            // ------------------------------------------------
            // 绘制粒子
            // ------------------------------------------------

            ctx.beginPath();


            ctx.arc(
                particle.screenX +
                this.planet.centerX,

                particle.screenY +
                this.planet.centerY,

                size,

                0,

                Math.PI * 2
            );


            ctx.fillStyle =
                `rgba(
                    ${color.r},
                    ${color.g},
                    ${color.b},
                    ${alpha}
                )`;


            ctx.fill();

        }

    }



    // ========================================================
    // Resize
    // ========================================================

    onResize() {

        this.resize();

        this.generate();

    }

}



// ============================================================
// 工具函数
// ============================================================



function randomRange(
    min,
    max
) {

    return (
        Math.random() *
        (
            max -
            min
        )
    ) + min;

}



// ============================================================
// 星环半径随机函数
// ============================================================

function randomRingRadius(
    inner,
    outer
) {

    // --------------------------------------------------------
    // 随机值
    // --------------------------------------------------------

    const value =
        Math.random();


    // --------------------------------------------------------
    // 非线性分布
    //
    // 让粒子不会机械地均匀铺满。
    // --------------------------------------------------------

    const curved =
        Math.pow(
            value,
            0.75
        );


    return (
        inner +
        (
            outer -
            inner
        ) *
        curved
    );

}
